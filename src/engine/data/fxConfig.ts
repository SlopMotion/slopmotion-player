/**
 * Trigger-only FX that shape a continuous amount from the hit envelope (pulse),
 * rather than firing a one-shot edge action (Jump Cut / Boomerang / …).
 */
const TRIGGER_ONLY_PULSE_AMOUNT_FX_KEYS = new Set<string>(["slowmo", "accelerate"]);

/** Playback FX driven only by per-param triggers (e.g. Cue Layer frame rows). */
const TRIGGER_NATIVE_FX_KEYS = new Set<string>(["playbackCue"]);

export function isTriggerOnlyFx(key: string): boolean {
  return TRIGGER_ONLY_FX_KEYS.has(key);
}

/** True when the trigger-only row should use a sustained pulse envelope (not square). */
export function isTriggerOnlyPulseAmountFx(key: string): boolean {
  return TRIGGER_ONLY_PULSE_AMOUNT_FX_KEYS.has(key);
}

export function isTriggerNativeFx(key: string): boolean {
  return TRIGGER_NATIVE_FX_KEYS.has(key);
}

export function hidesFxBaseRow(key: string): boolean {
  return isTriggerOnlyFx(key) || isTriggerNativeFx(key);
}

/** Tier for any addable FX key. Everything not Plus/Pro/Labs is free Starter. */
export function getFxTier(key: string): FxTier {
  if (FX_LABS_KEYS.has(key)) return "labs";
  if (FX_PRO_KEYS.has(key)) return "pro";
  if (FX_PLUS_KEYS.has(key)) return "plus";
  return "starter";
}

