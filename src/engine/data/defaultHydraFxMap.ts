/** Default `fx` map (`global.fx`, reset targets, preset baselines). */
export const createDefaultHydraFxMap = (): FolderConfig["fx"] => {
  const out = {} as FolderConfig["fx"];
  for (const key of Object.keys(HYDRA_FX_TEMPLATE_RAW) as (keyof FolderConfig["fx"])[]) {
    const template = HYDRA_FX_TEMPLATE_RAW[key];
    if (isCoreFxKey(key)) {
      out[key] = { ...template, ...PULSE_HIT_DEFAULTS };
    } else {
      out[key] = buildStaticFxConfig(key, template, template.enabled);
    }
  }
  return out;
};

/** Keys enabled on first run (the onboarding chain) — just the gentle reactive hero effect. */
export const ONBOARDING_ACTIVE_FX: (keyof FolderConfig["fx"])[] = ["pulse"];

/**
 * Fresh-install FX map: the default map plus the onboarding `pulse` effect enabled and
 * already reacting to the low band, so a first-time user immediately sees audio drive visuals.
 */
export const createOnboardingFxMap = (): FolderConfig["fx"] => {
  const fx = createDefaultHydraFxMap();
  fx.pulse = { ...HYDRA_FX_TEMPLATE_RAW.pulse, enabled: true };
  return fx;
};